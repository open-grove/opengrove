import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const projectRoot = resolve(import.meta.dirname, "..");
const protocolEntry = join(projectRoot, "packages", "protocol", "dist", "index.js");
const clientMapPath = join(projectRoot, "packages", "client", "client-map.json");
const outputPath = join(projectRoot, "packages", "client", "src", "generated", "client.ts");
const checkOnly = process.argv.includes("--check");

const [{ hostOperationGroups }, clientMapSource] = await Promise.all([
  import(`${pathToFileURL(protocolEntry).href}?generator=${Date.now()}`),
  readFile(clientMapPath, "utf8"),
]);
const clientMap = JSON.parse(clientMapSource);
const generated = renderClient(hostOperationGroups, clientMap);

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => undefined);
  if (current !== generated) {
    console.error("Generated Host Client is stale. Run: npm run generate:host-client");
    process.exit(1);
  }
  console.log("Generated Host Client is current.");
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
  console.log(
    `Generated ${relativeProjectPath(outputPath)} from ${hostOperationGroups.length} Host operation group(s).`,
  );
}

function renderClient(groups, names) {
  const tree = createTreeNode();
  const seenOperationIds = new Set();
  for (const group of groups) {
    const groupPath = clientPath(names.groups?.[group.id] ?? group.id, `group ${group.id}`);
    for (const resource of group.resources) {
      const resourceId = `${group.id}.${resource.id}`;
      const resourcePath = clientPath(names.resources?.[resourceId] ?? resource.id, `resource ${resourceId}`);
      const operationPrefix = `${resourceId}.`;
      for (const operation of resource.operations) {
        if (seenOperationIds.has(operation.id)) throw new Error(`Duplicate Host operation id: ${operation.id}`);
        seenOperationIds.add(operation.id);
        if (!operation.id.startsWith(operationPrefix)) {
          throw new Error(`Host operation ${operation.id} is outside resource ${resourceId}.`);
        }
        const defaultMethodName = operation.id.slice(operationPrefix.length);
        const methodPath = clientPath(
          names.operations?.[operation.id] ?? defaultMethodName,
          `operation ${operation.id}`,
        );
        const sections = {
          params: schemaFields(operation, "params"),
          query: schemaFields(operation, "query"),
          body: schemaFields(operation, "body"),
        };
        assertDisjointInputFields(operation.id, sections);
        addOperation(tree, [...groupPath, ...resourcePath, ...methodPath], {
          operation,
          sections,
          inputOptional: operationInputOptional(operation),
        });
      }
    }
  }

  return `// Generated by scripts/generate-host-client.mjs. Do not edit by hand.\nimport { hostOperationById, type HostOperationInput, type HostOperationOutput } from "#protocol";\nimport type { HostOperationRequest, OpenGroveRequestOptions } from "../transport.js";\n\nexport function bindOpenGroveClient(request: HostOperationRequest) {\n  return {\n    request,\n${renderTreeChildren(tree, 4)}\n  };\n}\n\nexport type OpenGroveClient = ReturnType<typeof bindOpenGroveClient>;\n`;
}

function createTreeNode() {
  return { children: new Map(), operation: undefined };
}

function addOperation(root, path, operation) {
  let node = root;
  for (const segment of path) {
    if (node.operation) throw new Error(`Client path ${path.join(".")} conflicts with an operation.`);
    let child = node.children.get(segment);
    if (!child) {
      child = createTreeNode();
      node.children.set(segment, child);
    }
    node = child;
  }
  if (node.operation || node.children.size) throw new Error(`Duplicate or conflicting Client path: ${path.join(".")}`);
  node.operation = operation;
}

function renderTreeChildren(node, indent) {
  return [...node.children.entries()]
    .map(([name, child]) => {
      const prefix = `${" ".repeat(indent)}${propertyName(name)}: `;
      if (child.operation) return `${prefix}${renderOperation(child.operation, indent)},`;
      return `${prefix}{\n${renderTreeChildren(child, indent + 2)}\n${" ".repeat(indent)}},`;
    })
    .join("\n");
}

function renderOperation(entry, indent) {
  const operationId = JSON.stringify(entry.operation.id);
  const operationType = `(typeof hostOperationById)[${operationId}]`;
  const hasInput = Object.values(entry.sections).some((fields) => fields !== undefined);
  const parameters = [];
  if (hasInput) {
    parameters.push(`input: HostOperationInput<${operationType}>${entry.inputOptional ? " = {}" : ""},`);
  }
  parameters.push("options?: OpenGroveRequestOptions,");
  const requestSections = Object.entries(entry.sections)
    .filter(([, fields]) => fields !== undefined)
    .map(([name, fields]) => renderRequestSection(name, fields, indent + 4));
  requestSections.push(`${" ".repeat(indent + 4)}signal: options?.signal,`);
  return `(\n${parameters.map((line) => `${" ".repeat(indent + 2)}${line}`).join("\n")}\n${" ".repeat(
    indent,
  )}): Promise<HostOperationOutput<${operationType}>> =>\n${" ".repeat(indent + 2)}request(hostOperationById[${operationId}], {\n${requestSections.join(
    "\n",
  )}\n${" ".repeat(indent + 2)}})`;
}

function renderRequestSection(name, fields, indent) {
  const properties = fields
    .map((field) => `${" ".repeat(indent + 2)}${propertyName(field)}: input${propertyAccess(field)},`)
    .join("\n");
  return `${" ".repeat(indent)}${name}: {\n${properties}\n${" ".repeat(indent)}},`;
}

function schemaFields(operation, section) {
  const schema = operation[section];
  if (!schema) return undefined;
  const shape = schema.shape;
  if (!shape || typeof shape !== "object") {
    throw new Error(`Host operation ${operation.id} ${section} must be a top-level object for Client generation.`);
  }
  return Object.keys(shape).sort();
}

function operationInputOptional(operation) {
  const schemas = [operation.params, operation.query, operation.body].filter(Boolean);
  return schemas.length > 0 && schemas.every((schema) => schema.safeParse({}).success);
}

function assertDisjointInputFields(operationId, sections) {
  const owners = new Map();
  for (const [section, fields] of Object.entries(sections)) {
    for (const field of fields ?? []) {
      const previous = owners.get(field);
      if (previous) {
        throw new Error(`Host operation ${operationId} field ${field} appears in both ${previous} and ${section}.`);
      }
      owners.set(field, section);
    }
  }
}

function clientPath(value, owner) {
  if (typeof value !== "string" || !value) throw new Error(`Missing Client name for ${owner}.`);
  const path = value.split(".");
  for (const segment of path) {
    if (!/^[$A-Z_a-z][$\w]*$/u.test(segment)) throw new Error(`Invalid Client name ${segment} for ${owner}.`);
  }
  return path;
}

function propertyName(value) {
  return /^[$A-Z_a-z][$\w]*$/u.test(value) ? value : JSON.stringify(value);
}

function propertyAccess(value) {
  return /^[$A-Z_a-z][$\w]*$/u.test(value) ? `.${value}` : `[${JSON.stringify(value)}]`;
}

function relativeProjectPath(path) {
  return path.slice(projectRoot.length + 1);
}
